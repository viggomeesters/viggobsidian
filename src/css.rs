//! Shared layout plus private destination identities, rendered by the package updater.
use crate::{Result, fail};
use serde_json::{Value, json};

/// Strip comments without touching quoted SVG data or braces in strings.
pub(crate) fn rules(css: &str) -> Result<Vec<String>> {
    let mut clean = String::new();
    let mut chars = css.chars().peekable();
    let mut quote = None;
    let mut escape = false;
    while let Some(c) = chars.next() {
        if escape {
            clean.push(c);
            escape = false;
            continue;
        }
        if c == '\\' {
            clean.push(c);
            escape = true;
            continue;
        }
        if let Some(q) = quote {
            clean.push(c);
            if c == q {
                quote = None;
            }
            continue;
        }
        if matches!(c, '\'' | '"') {
            quote = Some(c);
            clean.push(c);
            continue;
        }
        if c == '/' && chars.peek() == Some(&'*') {
            chars.next();
            let mut closed = false;
            while let Some(c) = chars.next() {
                if c == '*' && chars.peek() == Some(&'/') {
                    chars.next();
                    closed = true;
                    break;
                }
            }
            if !closed {
                return fail("unterminated CSS comment");
            }
            clean.push(' ');
        } else {
            clean.push(c);
        }
    }
    if quote.is_some() {
        return fail("unterminated CSS string");
    }
    let mut out = Vec::new();
    let mut start = 0;
    let mut depth = 0;
    let mut quote = None;
    let mut escape = false;
    for (offset, c) in clean.char_indices() {
        if escape {
            escape = false;
            continue;
        }
        if c == '\\' {
            escape = true;
            continue;
        }
        if let Some(q) = quote {
            if c == q {
                quote = None;
            }
            continue;
        }
        if matches!(c, '\'' | '"') {
            quote = Some(c);
            continue;
        }
        match c {
            '{' => depth += 1,
            '}' => {
                if depth == 0 {
                    return fail("unbalanced CSS");
                }
                depth -= 1;
                if depth == 0 {
                    out.push(clean[start..offset + 1].trim().to_string());
                    start = offset + 1;
                }
            }
            ';' if depth == 0 => return fail("top-level CSS statements need explicit migration"),
            _ => {}
        }
    }
    if depth != 0 || !clean[start..].trim().is_empty() {
        return fail("incomplete CSS rule");
    }
    Ok(out)
}

pub(crate) fn split(css: &str) -> Result<(Vec<String>, Vec<Value>)> {
    let mut shared = Vec::new();
    let mut routes = Vec::new();
    for rule in rules(css)? {
        let (header, body) = rule.split_once('{').ok_or("CSS rule without body")?;
        if header.trim_start().starts_with('@') {
            let (generic, local) = split(body.strip_suffix('}').ok_or("CSS closing brace")?)?;
            if !generic.is_empty() {
                shared.push(format!("{header}{{\n{}\n}}", generic.join("\n\n")));
            }
            for mut route in local {
                if !route["within"].is_null() {
                    return fail("nested route wrappers require explicit migration");
                }
                route["within"] = json!(header.trim());
                routes.push(route);
            }
        } else if header.contains("data-href") {
            routes.push(json!({"selectors":header.trim(),"declarations":body.strip_suffix('}').ok_or("CSS closing brace")?.trim()}));
        } else {
            shared.push(rule);
        }
    }
    Ok((shared, routes))
}
pub(crate) fn render(shared: &str, config: &Value) -> Result<Vec<u8>> {
    if config["schema"] != "viggobsidian.appearance.v1" {
        return fail("unknown local appearance schema");
    }
    let mut css = String::from(
        "/* Generated by ViggObsidian. Edit upstream CSS or local appearance.json, then preview/apply. */\n",
    );
    let human = config["human_alias"].as_str().unwrap_or("human");
    if human.is_empty() || !human.bytes().all(|b| b.is_ascii_lowercase() || b == b'-') {
        return fail("invalid local human_alias");
    }
    css.push_str(&shared.replace(
        "data-callout-metadata=\"human\"",
        &format!("data-callout-metadata=\"{human}\""),
    ));
    css.push_str("\n/* Local destination identities. */\n");
    for row in config["routes"]
        .as_array()
        .ok_or("missing appearance routes")?
    {
        let selectors = row["selectors"].as_str().ok_or("missing route selector")?;
        let declarations = row["declarations"]
            .as_str()
            .ok_or("missing route declarations")?;
        let rule = format!("{selectors} {{\n{declarations}\n}}");
        if rules(&rule)?.len() != 1
            || !(selectors.contains("data-href") || selectors.contains("data-callout-metadata"))
        {
            return fail("invalid destination rule");
        }
        let text = if let Some(within) = row["within"].as_str() {
            if !within.starts_with("@media ") && !within.starts_with("@supports ") {
                return fail("unsupported local route wrapper");
            }
            format!("{within} {{\n{rule}\n}}")
        } else {
            rule
        };
        if rules(&text)?.len() != 1 {
            return fail("invalid route wrapper");
        }
        css.push_str(&text);
        css.push('\n');
    }
    Ok(css.into_bytes())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn svg_strings_comments_and_nested_routes() {
        let input = "/* local */ .a { mask: url(\"data:svg,{/*literal*/}\"); } @media (max-width: 600px) { .x a[data-href=\"secret\"] { --dashboard-accent: red; } .b {display: block;} }";
        let (shared, routes) = split(input).unwrap();
        assert_eq!(shared.len(), 2);
        assert_eq!(routes.len(), 1);
        assert!(!shared.join("\n").contains("secret"));
        assert!(shared.join("\n").contains("/*literal*/"));
        let output = render(
            &shared.join("\n"),
            &json!({"schema":"viggobsidian.appearance.v1","routes":routes}),
        )
        .unwrap();
        assert!(
            String::from_utf8(output)
                .unwrap()
                .contains("@media (max-width: 600px)")
        );
    }
    #[test]
    fn malformed_css_and_injected_rules_are_rejected() {
        for css in [".x{", ".x{a:'oops}", "/*missing", "@import 'remote';"] {
            assert!(rules(css).is_err());
        }
        assert!(render("",&json!({"schema":"viggobsidian.appearance.v1","routes":[{"selectors":"a[data-href=x]","declarations":"} .secret {color:red"}]})).is_err());
    }
}
